//! Every step line used in the spec must parse.
use testkit::expr::parse::args;

#[test]
fn spec_lines_parse() {
    let lines = [
        ("visit", "/login"),
        ("visit", "${base_url}/orders"),
        ("fill", r#"field "Email" with "${user}""#),
        ("fill", r#"field "Password" with "${env.PASS}""#),
        ("click", r#"button "Sign in""#),
        ("click", r#"button "Delete" in row /Alice/"#),
        ("click", "<#search-form input/>"),
        ("click", "@e12"),
        ("click", "first link in navigation"),
        ("select", r#"field "Plan" with "Pro""#),
        ("type", r#""orders""#),
        ("press", "Enter"),
        ("press", "ctrl+c"),
        ("press", "down down down"),
        ("press", "down 3 times"),
        ("enter", r#""1.0.0""#),
        ("wait", "2s"),
        ("wait", "<.toast/> is visible"),
        ("wait", r#"for request "/api/me" or 5s"#),
        ("wait", r#"for text /listening on :(\d+)/ in server or 60s"#),
        ("wait", "for popup into checkout"),
        ("wait", r#"for text "package name:""#),
        ("wait", "for navigation"),
        ("expect", r#"heading "Dashboard" is visible"#),
        ("expect", "no console errors"),
        ("expect", r#"the status of request "POST /api/orders" is 201"#),
        ("expect", "no row /Alice/"),
        ("expect", r#"row /Alice/ matches cell "paid""#),
        ("expect", r#"table "Orders""#),
        ("expect", "screen"),
        ("expect", "json"),
        ("expect", r#"file "out/new.tk.yaml" exists"#),
        ("expect", "its exit is 1"),
        ("expect", "its stdout's json[0].step_error exists"),
        ("expect", "the exit of server is 0 within 5s"),
        ("expect", "no stderr in server"),
        ("expect", r#"text /order created id=\d+/ in server"#),
        ("expect", "the lcp of page is less than 2.5s"),
        ("expect", "the cls of page < 0.1"),
        ("expect", r#"the lcp of page is within 10% of baseline "home-lcp""#),
        ("expect", "its duration is less than 300ms"),
        ("expect", "no long tasks over 200ms"),
        ("expect", "no a11y violations"),
        ("expect", r#"the color of text "src/new_file.rs" is green"#),
        ("expect", "the cursor's row is 5"),
        ("expect", r#"no text "panic""#),
        ("expect", r#"alert "Order created" is visible"#),
        ("expect", r#"file "${tmp}/package.json"'s json's name is "demo-app""#),
        ("expect", "the exit of it is 0"),
        ("expect", r#"its stdout matches /^testkit \d+\.\d+\.\d+$/"#),
        ("expect", "$.resp.status == 200"),
        ("expect", "$.resp.status == $.env.STATUS"),
        ("expect", r#"the json contains "Alice""#),
        (
            "expect",
            r#"(the json mapped to its total) is (orders mapped to (its "Order Total" as Number))"#,
        ),
        ("expect", "the length of the json is the length of orders"),
        ("expect", r#"the @href of first <a/> contains "/docs""#),
        ("expect", "the length of <li/> in <#cart/> is 3"),
        ("expect", r#"<h1/>'s textContent is "Dashboard""#),
        ("expect", r#"the duration of every request "/api/**" is less than 500ms"#),
        ("expect", "its heap_growth is less than 5MB"),
        ("extract", "its match[1] into port"),
        ("extract", r#"the rows of table "Orders" into orders"#),
        ("extract", r#"the cookie "sid" into token"#),
        ("route", "POST /api/orders"),
        ("route", "/analytics/**"),
        ("call", "flows/login.tk.yaml"),
        ("claim", "A user can create an order"),
        ("shot", "dashboard.png"),
        ("shot", ""),
        ("snapshot", "main"),
        ("snapshot", ""),
        ("exec", "cargo run -- --version"),
        ("exec", "echo $${HOME} $HOME"),
        ("spawn", "cargo run -- serve --port 0"),
        ("signal", "SIGTERM to server"),
        ("resize", "80x24"),
        ("trace", "start"),
        ("trace", "stop into checkout"),
        ("heap", "snapshot into h1"),
        ("throttle", "cpu 4x"),
        ("network", "slow 3g"),
        ("emulate", "dark"),
        ("drag", r#"text "card" to region "Done""#),
        ("GET", "/api/orders/${order_id}"),
        ("expect", r#"some <li/> where its text contains "x""#),
    ];
    let bad: Vec<String> = lines
        .iter()
        .filter_map(|(v, s)| args(v, s).err().map(|e| format!("{v}: {s}\n{e}")))
        .collect();
    assert!(bad.is_empty(), "{}", bad.join("\n\n"));
}
